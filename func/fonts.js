// Build character lookup maps for fast transformation
const charMaps = {};
for (const [fontName, styledAlphabet] of Object.entries(fontMap)) {
  charMaps[fontName] = {};
  const styledChars = Array.from(styledAlphabet);
  for (let i = 0; i < normalAlphabet.length && i < styledChars.length; i++) {
    charMaps[fontName][normalAlphabet[i]] = styledChars[i];
  }
}

/**
 * Apply stylized font to text
 * @param {string} text - text to format
 * @param {string} font - font name
 * @returns {string} styled text
 */
function applyFont(text, font = "none") {
  if (!text || typeof text !== "string") return text || "";
  if (!font || font === "none" || font === "normal") return text;
  
  const map = charMaps[font] || charMaps.bold;
  if (!map) return text;
  
  return text.split("").map(ch => map[ch] || ch).join("");
}

/**
 * Format markdown **bold** parts with unicode bold
 * @param {string} text 
 * @param {string} font 
 * @returns {string}
 */
function autoBold(text, font = "bold") {
  if (!text || typeof text !== "string") return text || "";
  
  // Match bold syntax **text** or __text__
  return text.replace(/\*\*(.*?)\*\*|__(.*?)__/g, (_, p1, p2) => {
    const content = p1 || p2 || "";
    return applyFont(content, font);
  });
}

/**
 * Reverse styled unicode text back to normal ASCII text
 * @param {string} styledText 
 * @returns {string}
 */
function reverseFonts(styledText) {
  if (!styledText || typeof styledText !== "string") return styledText || "";

  // Reverse mapping lookup
  const reverseMap = {};
  for (const [fontName, map] of Object.entries(charMaps)) {
    for (const [normalChar, styledChar] of Object.entries(map)) {
      reverseMap[styledChar] = normalChar;
    }
  }

  return Array.from(styledText).map(ch => reverseMap[ch] || ch).join("");
}

